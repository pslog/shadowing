export const LOCALES = ["vi", "ja"] as const;

export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "vi";
export const LOCALE_COOKIE = "shadowing-jp-locale";
/** Request header the proxy stamps the URL locale onto, for server rendering. */
export const LOCALE_HEADER = "x-shadowing-locale";

export function isLocale(value: string | undefined | null): value is Locale {
  return LOCALES.includes(value as Locale);
}

export function localeFromPathname(pathname: string | null | undefined): Locale {
  const segment = pathname?.split("/").filter(Boolean)[0];
  return isLocale(segment) ? segment : DEFAULT_LOCALE;
}

export function stripLocale(pathname: string): string {
  const [path, hash = ""] = pathname.split("#");
  const [base, query = ""] = path.split("?");
  const parts = base.split("/").filter(Boolean);
  const stripped = isLocale(parts[0]) ? `/${parts.slice(1).join("/")}` : base;
  const normalized = stripped === "/" || stripped === "" ? "/" : stripped;
  return `${normalized}${query ? `?${query}` : ""}${hash ? `#${hash}` : ""}`;
}

export function withLocale(href: string, locale: Locale): string {
  if (
    href.startsWith("http://") ||
    href.startsWith("https://") ||
    href.startsWith("mailto:") ||
    href.startsWith("tel:") ||
    href.startsWith("#") ||
    href.startsWith("/api/")
  ) {
    return href;
  }

  const [path, hash = ""] = href.split("#");
  const [base, query = ""] = path.split("?");
  const stripped = stripLocale(base);
  const localizedBase = stripped === "/" ? `/${locale}` : `/${locale}${stripped}`;
  return `${localizedBase}${query ? `?${query}` : ""}${hash ? `#${hash}` : ""}`;
}

